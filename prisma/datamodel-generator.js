// A small Prisma generator: writes the schema's models — each field's kind,
// type, whether it's the id, unique or required, and the columns behind each
// relation — to src/generated/datamodel.ts. Prisma 6's client carried all of
// this as `Prisma.dmmf`; Prisma 7's doesn't, and backups and deleting an
// organisation (src/common/prisma/tenant-models.ts) work out what a tenant
// owns, and in what order, from it.
const { generatorHandler } = require('@prisma/generator-helper');
const { mkdirSync, writeFileSync } = require('node:fs');
const path = require('node:path');

generatorHandler({
  onManifest() {
    return { prettyName: 'Roomick data model', defaultOutput: '../src/generated/datamodel.ts' };
  },
  async onGenerate(options) {
    const models = options.dmmf.datamodel.models.map((model) => ({
      name: model.name,
      fields: model.fields.map((field) => ({
        name: field.name,
        kind: field.kind,
        type: field.type,
        isId: field.isId,
        isUnique: field.isUnique,
        isRequired: field.isRequired,
        ...(field.relationFromFields && field.relationFromFields.length > 0 ? { relationFromFields: [...field.relationFromFields] } : {}),
      })),
    }));
    const output = options.generator.output.value;
    mkdirSync(path.dirname(output), { recursive: true });
    writeFileSync(
      output,
      [
        '/* Generated by prisma/datamodel-generator.js from prisma/schema.prisma — do not edit. */',
        '',
        'export interface DatamodelField {',
        '  name: string;',
        "  kind: 'scalar' | 'object' | 'enum' | 'unsupported';",
        '  type: string;',
        '  isId: boolean;',
        '  isUnique: boolean;',
        '  isRequired: boolean;',
        '  relationFromFields?: string[];',
        '}',
        '',
        'export interface DatamodelModel {',
        '  name: string;',
        '  fields: DatamodelField[];',
        '}',
        '',
        `export const DATAMODEL_MODELS: DatamodelModel[] = ${JSON.stringify(models, null, 2)};`,
        '',
      ].join('\n'),
    );
  },
});
